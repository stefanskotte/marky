#!/usr/bin/env python3
"""Builds Shared/Resources/github.css from github-markdown-css's github-markdown.css.

  scripts/vendor-github-css.py <path to github-markdown.css> [version]

Upstream switches light/dark only through prefers-color-scheme. Marky also forces a theme with
<html data-theme="light|dark"> (Quick Look follows the app's Appearance setting), so the two colour
blocks are rewritten to the same selectors markdown.css uses, and moved to :root so the page
background around the article can use them too. Everything else is kept as is.
"""
import re
import sys

src_path = sys.argv[1]
version = sys.argv[2] if len(sys.argv) > 2 else "?"
css = open(src_path, encoding="utf-8").read()


def block(scheme):
    m = re.search(r"@media \(prefers-color-scheme: %s\) \{\s*\.markdown-body, \[data-theme=\"%s\"\] \{(.*?)\n  \}\n\}\n"
                  % (scheme, scheme), css, re.S)
    if not m:
        sys.exit(f"vendor-github-css: no {scheme} block found; upstream format changed")
    return m


dark, light = block("dark"), block("light")
body = lambda m: m.group(1).replace("\n    ", "\n  ").rstrip()
themes = (
    f":root {{{body(light)}\n}}\n"
    f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{{body(dark).replace(chr(10), chr(10) + '  ')}\n  }}\n}}\n"
    f":root[data-theme=\"dark\"] {{{body(dark)}\n}}\n"
)
rest = css.replace(dark.group(0), "").replace(light.group(0), "")
# The first rule holds base variables (incl. --fgColor-accent: Highlight). On .markdown-body it would
# override the theme colours on :root, so it moves to :root as well, ahead of them.
if not rest.startswith(".markdown-body {"):
    sys.exit("vendor-github-css: first rule is not the .markdown-body variables; upstream format changed")
rest = ":root {" + rest[len(".markdown-body {"):]
# The theme blocks sat right after the first .markdown-body {...} rule; put them back there.
first_end = rest.index("}\n") + 2
out = (
    f"/* github-markdown-css {version} by Sindre Sorhus (MIT), https://github.com/sindresorhus/github-markdown-css\n"
    f"   Generated by scripts/vendor-github-css.py: colour blocks moved to :root and data-theme. */\n"
    + rest[:first_end] + themes + rest[first_end:]
)
open("Shared/Resources/github.css", "w", encoding="utf-8").write(out)
print(f"github.css: {len(out)} bytes")
